export function buildUserPrompt(input: ReviewRequest) {
  const focus = input.focus.trim()
    ? `疗愈师最想复盘的问题（必须重点回答）：\n${input.focus.trim()}\n\n`
    : "疗愈师未填写聚焦问题。按会谈内容自行抓住最关键的专业问题。\n\n";

  return `个案名称（代号）：${input.caseName}
第 ${input.sessionNumber} 次会谈

${focus}会谈内容：
${input.transcript}`;
}
